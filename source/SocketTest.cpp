void SocketTest::testExtendedSerializer(){

	std::vector<char> buffer;

	// --- Test 1: Simple Pair ---
	std::pair<int, std::string> p1 = { 42, "forty-two" };
	serializeArg(buffer, p1);

	const char* data = buffer.data();
	auto p1_out = deserializeArg<std::pair<int, std::string>>(data);
	assert(p1_out.first == 42);
	assert(p1_out.second == "forty-two");
	buffer.clear();

	std::cout << "Pair test passed \n";

	// --- Test 2: Tuple ---
	std::tuple<int, float, std::string> t1 = { 10, 3.14f, "tuple!" };
	serializeArg(buffer, t1);

	data = buffer.data();
	auto t1_out = deserializeArg<std::tuple<int, float, std::string>>(data);
	assert(std::get<0>(t1_out) == 10);
	assert(std::get<1>(t1_out) == 3.14f);
	assert(std::get<2>(t1_out) == "tuple!");
	buffer.clear();

	std::cout << "Tuple test passed \n";

	// --- Test 3: Map ---
	std::map<int, std::string> m1 = { {1, "one"}, {2, "two"}, {3, "three"} };
	serializeArg(buffer, m1);

	data = buffer.data();
	auto m1_out = deserializeArg<std::map<int, std::string>>(data);
	assert(m1_out == m1);
	buffer.clear();

	std::cout << "Map test passed \n";

	// --- Test 4: Unordered Map ---
	std::unordered_map<std::string, int> um1 = { {"apple", 1}, {"banana", 2}, {"cherry", 3} };
	serializeArg(buffer, um1);

	data = buffer.data();
	auto um1_out = deserializeArg<std::unordered_map<std::string, int>>(data);
	assert(um1_out.size() == um1.size());
	for (auto& kv : um1){
		assert(um1_out.at(kv.first) == kv.second);
	}
	buffer.clear();

	std::cout << "Unordered Map test passed \n";

	// --- Test 5: Set ---
	std::set<int> s1 = { 1, 5, 9 };
	serializeArg(buffer, s1);

	data = buffer.data();
	auto s1_out = deserializeArg<std::set<int>>(data);
	assert(s1_out == s1);
	buffer.clear();

	std::cout << "Set test passed \n";

	// --- Test 6: Unordered Set ---
	std::unordered_set<std::string> us1 = { "red", "green", "blue" };
	serializeArg(buffer, us1);

	data = buffer.data();
	auto us1_out = deserializeArg<std::unordered_set<std::string>>(data);
	assert(us1_out.size() == us1.size());
	for (auto& v : us1) assert(us1_out.contains(v));
	buffer.clear();

	std::cout << "Unordered Set test passed \n";

	// --- Test 7: Nested Structure ---
	std::unordered_map<std::string, std::vector<std::pair<int, std::set<std::string>>>> nested;
	nested["group1"] = {
		{1, {"a", "b"}},
		{2, {"x", "y", "z"}}
	};
	nested["group2"] = {
		{10, {"cat", "dog"}},
		{11, {"mouse"}}
	};

	serializeArg(buffer, nested);

	data = buffer.data();
	auto nested_out = deserializeArg<std::unordered_map<std::string, std::vector<std::pair<int, std::set<std::string>>>>>(data);

	assert(nested_out.size() == nested.size());
	for (auto& kv : nested) {
		auto& out_vec = nested_out.at(kv.first);
		auto& in_vec = kv.second;
		assert(out_vec.size() == in_vec.size());
		for (size_t i = 0; i < in_vec.size(); i++) {
			assert(out_vec[i].first == in_vec[i].first);
			assert(out_vec[i].second == in_vec[i].second);
		}
	}
	buffer.clear();

	std::cout << "Nested container test passed \n";

	std::cout << "\nAll serialization tests passed \n";
}