//Called when a packet is received
void SocketTest::Receiver::receivePacket(int sender_id, const std::vector<char>& data){
	try {
	std::shared_ptr<TestPacket> r = static_pointer_cast<TestPacket>(SocketTest::registry.deserializeObj(SocketTest::PACKET_ID, data)) ;


	printf("Got packet from id=%d  name=%s number=%d message=%s: \n", sender_id, r->source.c_str(), r->number, r->message.c_str());
	packet.message = "number++";
	packet.number++;
	std::vector<char> serial = SocketTest::registry.serializeObj(SocketTest::PACKET_ID, &packet) ;
	socket->send(sender_id, serial);
	}
	catch (const std::runtime_error& e) {
		std::cerr << "Caught a runtime error on packet retrieval: " << e.what() << std::endl;
	}
	catch(...){
		std::cerr << "unknown exception on packet retrieval" << std::endl;
	}
}

//Called when a connection is established, 
//sender_id is generated by the socket and can be used to identify recieved packet sources or send data back through the socket
