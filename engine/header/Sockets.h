// Structure to hold queued outgoing packet
struct PendingPacket {
	std::vector<char> data;
	std::shared_ptr<sockaddr_in> addr;
};


// An abstract socket that could be either client or server
class Socket {
	public:
		// Send data through this socket
		// Returns if data seems to have sent (we can't know now if it arrived)
		virtual bool send(int receiver_id, const std::vector<char>& data) = 0;

		// close all connections in this socket and stop allowing new ones if applicable
		virtual void close() = 0;
	
		//Set the object that will get packets when they are sent to this socket
		virtual void setPacketReceiver(PacketReceiver* receiver) = 0 ;

		//Loops to make sure all of the bytes go through on a send (for TCP only)
		static bool sendAll(SOCKET socket, const char* source, int num_bytes);

		//Loops to make sure all of the bytes get read on a recv (for TCP only)
		static bool recvAll(SOCKET socket, char* destination, int num_bytes);
};

//An abstract interface that can be overwridden to get socket data forwarded to custom classes
class PacketReceiver {
public:

	//Called when a packet is received
	virtual void receivePacket(int sender_id, const std::vector<char>& data) = 0;
	
	//Called when a connection is established, 
	//sender_id is generated by the socket and can be used to identify recieved packet sources or send data back through the socket
	virtual void onSocketConnect(int sender_id) = 0 ;

	//Called when a connection is closed, either remotely or because the socket holding it was closed
	virtual void  onSocketClose(int sender_id) = 0 ;

};

//A wrapper for a packet receiver that simulates lag by holding packets to deliver
//Careful to not allocate this on the stack as it creates a thread on itself, use a shared_ptr
class SlowPacketReceiver: public PacketReceiver {
public:
	
	

	struct SlowPacket{
		int sender = -1 ;
		std::chrono::high_resolution_clock::time_point arrival_time ;
		std::vector<char> data ;
		SlowPacket(int s, std::chrono::high_resolution_clock::time_point a, const std::vector<char>& d){
			sender =s ;
			arrival_time = a;
			data = d ;
			if(d.size() == 0){
				printf("completely empty packet!?\n");
			}
		}
	};

	std::queue<std::shared_ptr<SlowPacket>> packets ;

	SlowPacketReceiver(PacketReceiver* r, int micros_of_delay, int micros_of_jitter) ;

	//Called when a packet is received
	void receivePacket(int sender_id, const std::vector<char>& data) override;

	//Called when a connection is established, 
	//sender_id is generated by the socket and can be used to identify recieved packet sources or send data back through the socket
	void onSocketConnect(int sender_id) override;

	//Called when a connection is closed, either remotely or because the socket holding it was closed
	void  onSocketClose(int sender_id) override;



	void stop();

private:
	PacketReceiver* receiver;
	std::thread thread;
	std::recursive_mutex lock;
	int lag_micros = 0;
	int jitter_micros = 0 ;
	int next_jitter = 0 ;
	bool stopped = false;
	//runs the thread to deliver the packet withthe delay
	void run();
};


